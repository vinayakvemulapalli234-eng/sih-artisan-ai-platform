const APP_LANG_KEY = 'kalakriti_app_language';

export function getAppLanguage() {
  try {
    return localStorage.getItem(APP_LANG_KEY) || 'en';
  } catch {
    return 'en';
  }
}

export function setAppLanguage(langCode) {
  try {
    localStorage.setItem(APP_LANG_KEY, langCode);
  } catch (err) {
    console.error('Failed to set language', err);
  }
}

export function t(key, lang = null) {
  const currentLang = lang || getAppLanguage();
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}
